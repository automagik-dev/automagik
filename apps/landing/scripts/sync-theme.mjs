// The static landing consumes the app's Stage palette and component tokens, and the brand's
// title face and status colours: docs/brand/tokens/tokens.json names the face, its three weights,
// its font file and the status colours, and docs/brand/fonts holds the file. Regenerate after an intentional app-theme or brand update;
// --check detects drift in CI.
import assert from 'node:assert/strict'
import { readFile, writeFile, copyFile } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { STAGE_CSS, STAGE_LIGHT, STAGE_DARK } from '../../bots-dsh/src/client/stage.js'

const brand = new URL('../../../docs/brand/', import.meta.url)
const { type, color } = JSON.parse(readFileSync(new URL('tokens/tokens.json', brand), 'utf8'))
// The status colours are the brand's too. The app's theme still carries its own copy of them.
export const statusNames = ['st-ok', 'st-okdot', 'st-bad', 'st-warn', 'st-warndot', 'st-work', 'bt-danger', 'bt-green']
const statusOf = theme => statusNames.map(name => {
  const value = color.tokens.find(token => token.name === name)?.value[theme]
  assert.match(value ?? '', /^#[0-9a-f]{6}$/, `docs/brand/tokens/tokens.json has no ${theme} colour for ${name}`)
  return [name, value]
})
// The title face is the first family of the head stack; its file sits in docs/brand/fonts.
export const titleFace = type.fonts.find(font => type.families.head.startsWith(`${font.family},`))
assert.ok(titleFace?.file.startsWith('fonts/') && titleFace.license, 'docs/brand/tokens/tokens.json names no title face with a file and a licence')
const fontFile = titleFace.file.slice('fonts/'.length)
// The brand's font and its licence, and where the site serves them from.
export const brandFonts = [fontFile, titleFace.license].map(name => ({ from: new URL(`fonts/${name}`, brand), to: new URL(`../assets/brand/${name}`, import.meta.url) }))
const weights = type.weights.map(weight => `--${weight.name}:${weight.value}`).join(';')

export function themeCss() {
  // The app still sets its own title face; the site takes the brand's.
  const headFont = `--bt-head-font:${type.families.head.replaceAll(', ', ',')};`
  const stage = (block, theme) => {
    assert.equal(block.match(/--bt-head-font:[^;]+;/g)?.length ?? 0, block.includes('--bt-head-font:') ? 1 : 0)
    for (const [name, value] of statusOf(theme)) {
      const own = new RegExp(`--${name}:#[0-9a-f]{6}(?![0-9a-f])`, 'g')
      assert.equal(block.match(own)?.length, 1, `the Stage theme sets --${name} ${block.match(own)?.length ?? 0} times in ${theme}`)
      block = block.replace(own, `--${name}:${value}`)
    }
    return block.replace(/--bt-head-font:[^;]+;/, headFont)
  }
  const light = stage(STAGE_CSS.match(/html body\{([\s\S]*?)\}/)[1], 'light')
  const dark = stage(STAGE_CSS.match(/html body\[data-ds-dark-theme\]\{([\s\S]*?)\}/)[1], 'dark')
  assert.ok(light.includes(headFont), 'the Stage theme no longer sets --bt-head-font')
  const vars = mode => `--bt-main:${mode.bg};--bt-sidebar:${mode.sidebar};--bt-bubble:${mode.bubble};--bt-card:${mode.card};--bt-ink:${mode.text};--bt-user:${mode.user};--bt-user-ink:${mode.userText};--bt-accent:${mode.accent};`
  return `/* Generated by scripts/sync-theme.mjs from the app's Stage theme and docs/brand/tokens/tokens.json. */
@font-face{font-family:"DM Sans";font-style:normal;font-weight:100 1000;font-display:swap;src:url("assets/brand/dm-sans-latin.woff2") format("woff2")}
@font-face{font-family:${titleFace.family};font-style:${titleFace.style};font-weight:${titleFace.weight};font-display:swap;size-adjust:${titleFace.sizeAdjust};src:url("assets/brand/${fontFile}") format("woff2")}
:root{color-scheme:light;${weights};${vars(STAGE_LIGHT)}${light}}
@media (prefers-color-scheme:dark){:root{color-scheme:dark;${vars(STAGE_DARK)}${dark}}}
`
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../theme.css', import.meta.url)
  if (process.argv[2] === '--check') {
    assert.equal(await readFile(target, 'utf8'), themeCss(), 'Landing theme drift: run node apps/landing/scripts/sync-theme.mjs')
    for (const { from, to } of brandFonts) assert.ok((await readFile(to)).equals(await readFile(from)), `Landing font drift: run node apps/landing/scripts/sync-theme.mjs (${to.pathname.split('/').pop()})`)
  } else {
    await writeFile(target, themeCss())
    for (const { from, to } of brandFonts) await copyFile(from, to)
  }
}
