// The static landing consumes the app's Stage palette, type and component tokens.
// Regenerate after an intentional app-theme update; --check detects drift in CI.
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { STAGE_CSS, STAGE_LIGHT, STAGE_DARK } from '../../bots-dsh/src/client/stage.js'

export function themeCss() {
  const light = STAGE_CSS.match(/html body\{([\s\S]*?)\}/)[1]
  const dark = STAGE_CSS.match(/html body\[data-ds-dark-theme\]\{([\s\S]*?)\}/)[1]
  const vars = mode => `--bt-main:${mode.bg};--bt-sidebar:${mode.sidebar};--bt-bubble:${mode.bubble};--bt-card:${mode.card};--bt-ink:${mode.text};--bt-user:${mode.user};--bt-user-ink:${mode.userText};--bt-accent:${mode.accent};`
  return `/* Generated by scripts/sync-theme.mjs from the app's Stage theme. */
@font-face{font-family:"DM Sans";font-style:normal;font-weight:100 1000;font-display:swap;src:url("assets/brand/dm-sans-latin.woff2") format("woff2")}
@font-face{font-family:Manrope;font-style:normal;font-weight:200 800;font-display:swap;src:url("assets/brand/manrope-latin.woff2") format("woff2")}
:root{color-scheme:light;${vars(STAGE_LIGHT)}${light}}
@media (prefers-color-scheme:dark){:root{color-scheme:dark;${vars(STAGE_DARK)}${dark}}}
`
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../theme.css', import.meta.url)
  if (process.argv[2] === '--check') assert.equal(await readFile(target, 'utf8'), themeCss(), 'Landing theme drift: run node apps/landing/scripts/sync-theme.mjs')
  else await writeFile(target, themeCss())
}
