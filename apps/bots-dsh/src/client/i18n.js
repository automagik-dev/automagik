export function hostTemplateOf(message) {
  return HOST_TEMPLATES.find(({ pattern }) => pattern.test(message))?.template
}
function hostTemplate(message) {
  const matched = hostTemplateOf(message)
  if (matched === undefined) return undefined
  const { template, names, host, pattern } = HOST_TEMPLATES.find(entry => entry.template === matched)
  const found = pattern.exec(message)
  return t(template, Object.fromEntries(names.map((name, index) => [name, host.includes(name) ? hostText(found[index + 1]) : found[index + 1]])))
}

// A message from the host, in the interface language.
export function hostText(message) {
  if (typeof message === 'string' && (bound || language().startsWith('zh'))) {
    const worded = hostTemplate(message)
    if (worded !== undefined) return worded
  }
  // A language pack that words this message (any language: the pt-BR pack, a plugin's
  // addStrings) wins; the patterns below are for Chinese only.
  if (bound && typeof message === 'string') {
    const worded = t(message)
    if (worded !== message) return worded
  }
  if (!language().startsWith('zh')) return message
  if (Object.hasOwn(ZH, message)) return t(message)
  for (const [pattern, template] of HOST_ERRORS) {
    if (pattern.test(message)) return message.replace(pattern, template)
  }
  return message
}

