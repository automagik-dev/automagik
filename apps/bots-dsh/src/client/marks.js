/** An ACP or Herdr agent's own mark, or its initial when no official mark is known. */
export function AgentMark({ id, name = '', size = 16 }) {
  const key = String(id ?? '').replace(/^acp-/, '')
  const src = AGENT_MARK[key]
  if (src === undefined) {
    return h('span', { className: 'bt-agent-initial', 'aria-hidden': true, style: { width: size, height: size, fontSize: Math.round(size * 0.62) } }, (name || key || '?').slice(0, 1).toUpperCase())
  }
  return h('img', { className: 'bt-agent-mark', src, width: size, height: size, alt: '', 'aria-hidden': true, draggable: false })
}
